const BY_KIND = new Map<EnemyKind, BestiaryEntry>(BESTIARY.map((e) => [e.kind, e]));

/** Карточка вида или null: у кокона, бабочки и половинок сколопендры своих карточек нет. */
export function bestiaryEntry(kind: EnemyKind): BestiaryEntry | null {
  return BY_KIND.get(kind) ?? null;
}

let homes: Map<EnemyKind, number> | null = null;

/** В каком акте вид впервые выходит в волнах кампании; у тех, кого в волнах нет, акт их «родителя». */
export function homeAct(kind: EnemyKind): number {
  if (!homes) {
    const m = new Map<EnemyKind, number>();
    LEVELS.forEach((lv, i) => {
      const a = LEVEL_ACT[i] ?? 0;
      for (const w of lv.waves) for (const g of w.groups) if (!m.has(g.kind)) m.set(g.kind, a);
    });
    for (const e of BESTIARY) {
      const a = m.get(e.kind) ?? 0;
      for (const f of e.forms ?? []) if (!m.has(f)) m.set(f, a);
    }
    homes = m;
  }
  return Math.min(homes.get(kind) ?? 0, ACTS.length - 1);
}

/** Шкала из пяти делений для карточки: здоровье, панцирь, скорость и удар по защитникам. */
export function foeStats(kind: EnemyKind): { hp: number; armor: number; speed: number; hit: number } {
  const d = ENEMIES[kind];
  const step = (v: number, edges: readonly number[]): number => {
    let n = 0;
    while (n < edges.length && v > edges[n]) n++;
    return n;
  };
  const dps = ((d.meleeDmg[0] + d.meleeDmg[1]) / 2) / d.meleeInterval;
  return {
    hp: 1 + step(d.hp, [50, 100, 180, 400]),
    armor: d.armor <= 0 ? 0 : 1 + step(d.armor, [0.15, 0.25, 0.35, 0.45]),
    speed: 1 + step(d.speed, [26, 46, 66, 86]),
    hit: dps <= 0 ? 0 : 1 + step(dps, [5, 8, 12, 20]),
  };
}
